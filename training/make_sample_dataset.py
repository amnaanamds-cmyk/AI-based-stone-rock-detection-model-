"""Create a small SYNTHETIC sample dataset so the training pipeline can be tried without real data.

    python training/make_sample_dataset.py

It writes dataset/raw/sample_synthetic/ (image.tif, labels.tif, dem.tif) generated by
rockmap/synthetic.py: made-up rock units with realistic spectra, terrain, snow and cloud. A model
trained on it proves that the pipeline works end to end - it is NOT a model of real geology, and
every model trained only on it is flagged "sample data" in its report and in the application.
Delete the folder once you have real data.
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from training import config                            # noqa: E402
from training.dataset import SAMPLE_MARKER             # noqa: E402

from rockmap.synthetic import write_scene              # noqa: E402


def main(argv=None) -> Path:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(config.DATA_DIR / "sample_synthetic"))
    ap.add_argument("--size", type=int, default=384, help="image size in pixels (default %(default)s)")
    ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    tmp = out / "_generating"
    paths = write_scene(tmp, a.size, a.size, a.seed)
    for key, name in (("scene", "image.tif"), ("reference", "labels.tif"), ("dem", "dem.tif")):
        shutil.move(str(paths[key]), out / name)
    shutil.rmtree(tmp, ignore_errors=True)
    (out / SAMPLE_MARKER).write_text(
        "SYNTHETIC SAMPLE DATA - generated by training/make_sample_dataset.py.\n"
        "The rock units, spectra and terrain are simulated. Models trained only on this folder are flagged\n"
        "as sample-data models and must not be used for real geological mapping.\n"
        "Delete this folder when you have your own dataset.\n", encoding="utf-8")
    print(f"Sample dataset written to {out} ({a.size} x {a.size} px). Next: python training/train.py")
    return out


if __name__ == "__main__":
    main()
